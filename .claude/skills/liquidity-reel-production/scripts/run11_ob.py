def gchart(seed, anchors, Ng, iob, imp, kind, Wd=880, H=270):
    W, zt, zb, sl, ra = ob_base(seed, anchors, Ng, iob, imp, label=f"دليل بلوك {kind}")
    ymin = min(c["l"] for c in W); ymax = max(c["h"] for c in W)
    if kind == "win":
        clamp_after(W, imp+1, Ng, zt, zb, ra, ret=(int(Ng*0.72), int(Ng*0.72)+2))
    elif kind == "entry":
        clamp_after(W, imp+1, Ng, zt, zb, ra, ret=(int(Ng*0.68), int(Ng*0.68)+3))
    elif kind == "wrong":
        clamp_after(W, imp+1, Ng, zt, zb, ra, ret=(int(Ng*0.7), int(Ng*0.7)+3))
    elif kind == "retest2":
        clamp_after(W, imp+1, Ng, zt, zb, ra, ret=(int(Ng*0.55), int(Ng*0.55)+2))
        for j in range(int(Ng*0.82), Ng):   # الاختبار الثاني يخترق
            W[j]["c"] = min(W[j]["c"], zb - ra*0.05 - (j-int(Ng*0.82))*ra*0.05)
            W[j]["l"] = min(W[j]["l"], W[j]["c"] - ra*0.02)
            W[j]["o"] = min(W[j]["o"], zt + ra*0.02)
            W[j]["h"] = max(W[j]["o"], W[j]["c"]) + ra*0.02
    elif kind == "nobos":
        for j in range(imp+1, Ng):          # يفشل: ينزل ويخترق البلوك
            W[j]["c"] = min(W[j]["c"], zb - (j-imp)*ra*0.045)
            W[j]["l"] = min(W[j]["l"], W[j]["c"] - ra*0.02)
            W[j]["o"] = min(W[j]["o"], zt + ra*0.03)
            W[j]["h"] = max(W[j]["o"], W[j]["c"]) + ra*0.02
    ymin = min(min(c["l"] for c in W), sl) - ra*0.08
    ymax = max(c["h"] for c in W) + ra*0.1
    svg, xg, yg, sg = chart(W, Wd, H, ymin, ymax, pl=12, pr=16, pt=20, pb=14, body=0.6)
    zx0g = xg(iob)-sg*0.55; zx1g = xg(Ng-1)+sg*0.5
    dash = ' stroke-dasharray="7 5"' if kind == "nobos" else ""
    svg += (f'<rect x="{zx0g:.1f}" y="{yg(zt):.1f}" width="{zx1g-zx0g:.1f}" height="{yg(zb)-yg(zt):.1f}"'
            f' fill="{TEAL}" opacity="0.12"/>'
            f'<rect x="{zx0g:.1f}" y="{yg(zt):.1f}" width="{zx1g-zx0g:.1f}" height="{yg(zb)-yg(zt):.1f}"'
            f' fill="none" stroke="{TEAL_D}" stroke-width="1.2"{dash}/>')
    svg += htext(xg(Ng-3), (yg(zt)+yg(zb))/2+7, "OB", TEAL_D, 17)
    if kind in ("win", "entry", "wrong"):
        ish = max(range(int(iob*0.55), iob-1), key=lambda j: W[j]["h"])
        svg += f'<line x1="{xg(ish)-sg*0.5:.1f}" y1="{yg(W[ish]["h"]):.1f}" x2="{xg(imp)+sg*0.5:.1f}" y2="{yg(W[ish]["h"]):.1f}" stroke="{INK}" stroke-width="1.7"/>'
        svg += htext(xg(ish)+sg*2.2, yg(W[ish]["h"])-11, "BOS", INK, 17)
    if kind == "wrong":
        wt = W[max(range(int(iob*0.5), iob), key=lambda j: W[j]["h"])]
        wz_t = wt["h"]; wz_b = max(wt["o"], wt["c"])
        svg += (f'<rect x="{zx0g:.1f}" y="{yg(wz_t):.1f}" width="{zx1g-zx0g:.1f}" height="{max(yg(wz_b)-yg(wz_t), 14):.1f}"'
                f' fill="{RED}" opacity="0.07"/>'
                f'<rect x="{zx0g:.1f}" y="{yg(wz_t):.1f}" width="{zx1g-zx0g:.1f}" height="{max(yg(wz_b)-yg(wz_t), 14):.1f}"'
                f' fill="none" stroke="{RED}" stroke-width="1.2" stroke-dasharray="6 5"/>')
        svg += htext(xg(Ng-5), yg(wz_t)-9, "رسمٌ من القمة ✗", RED, 17)
    if kind == "nobos":
        bx, by = xg(int(Ng*0.8)), yg(zb)
        svg += (f'<g stroke="{RED}" stroke-width="3" stroke-linecap="round">'
                f'<line x1="{bx-10:.1f}" y1="{by-10:.1f}" x2="{bx+10:.1f}" y2="{by+10:.1f}"/>'
                f'<line x1="{bx-10:.1f}" y1="{by+10:.1f}" x2="{bx+10:.1f}" y2="{by-10:.1f}"/></g>')
        svg += htext(xg(int(Ng*0.5)), yg(max(c["h"] for c in W))+2, "بلا كسر هيكل", MUTE, 17)
    if kind == "retest2":
        r1 = int(Ng*0.56); r2 = int(Ng*0.86)
        svg += f'<polyline points="{xg(r1)-9},{yg(zt)-26} {xg(r1)-2},{yg(zt)-18} {xg(r1)+11},{yg(zt)-32}" fill="none" stroke="{TEAL_D}" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>'
        bx, by = xg(r2), yg(zb)
        svg += (f'<g stroke="{RED}" stroke-width="3" stroke-linecap="round">'
                f'<line x1="{bx-10:.1f}" y1="{by-10:.1f}" x2="{bx+10:.1f}" y2="{by+10:.1f}"/>'
                f'<line x1="{bx-10:.1f}" y1="{by+10:.1f}" x2="{bx+10:.1f}" y2="{by-10:.1f}"/></g>')
    if kind == "entry":
        ret0 = int(Ng*0.68)
        x0e = xg(ret0-1)-sg*0.5; x1e = xg(Ng-1)+sg*0.5
        TGT = max(c["h"] for c in W[int(Ng*0.85):]) + ra*0.02
        svg += f'<line x1="{x0e:.1f}" y1="{yg(zt):.1f}" x2="{x1e:.1f}" y2="{yg(zt):.1f}" stroke="{INK}" stroke-width="2" opacity="0.9"/>'
        svg += f'<line x1="{x0e:.1f}" y1="{yg(sl):.1f}" x2="{x1e:.1f}" y2="{yg(sl):.1f}" stroke="{RED}" stroke-width="1.6" opacity="0.75"/>'
        svg += f'<line x1="{x0e:.1f}" y1="{yg(TGT):.1f}" x2="{x1e:.1f}" y2="{yg(TGT):.1f}" stroke="{TEAL}" stroke-width="1.6" opacity="0.85"/>'
        svg += htext(x1e-62, yg(zt)+24, "الدخول", INK, 17)
        svg += htext(x1e-58, yg(sl)+21, "الوقف", RED, 17)
        svg += htext(x0e+54, yg(TGT)-9, "الهدف", TEAL_D, 17)
    return svg + "</svg>"

