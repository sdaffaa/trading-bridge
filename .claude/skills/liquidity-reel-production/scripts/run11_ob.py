def ob_base(seed, anchors, N, iob, imp, wick=0.8, label=""):
    """قصة أوردر بلوك: يفرض آخر شمعة بائعة عند iob واندفاعاً صاعداً حتى imp، ويعيد سلسلة ما بعده."""
    _fresh(seed, anchors, label or f"ob-{seed}")
    W = gen(anchors, N, seed, wick=wick)
    ys = [a[1] for a in anchors]
    ra = max(ys) - min(ys)
    body = ra * 0.14
    o = W[iob-1]["c"]
    W[iob].update(o=o, c=o-body, h=o+body*0.3, l=o-body*1.4)
    old_c = W[imp]["c"]
    prev = W[iob]["c"]
    for j in range(iob+1, imp+1):
        step = ra * (0.22 if j == iob+1 else 0.15)
        W[j].update(o=prev, c=prev+step, h=prev+step+ra*0.03, l=prev-ra*0.02)
        prev = W[j]["c"]
    d = W[imp]["c"] - old_c
    for j in range(imp+1, N):
        for k in ("o", "h", "l", "c"):
            W[j][k] += d
    ZT, ZB = W[iob]["o"], W[iob]["c"]
    SL = W[iob]["l"] - ra * 0.06
    return W, ZT, ZB, SL, ra

def clamp_after(W, i0, i1, ZT, ZB, ra, ret=None):
    """ما بعد الاندفاع فوق البلوك، إلا نافذة العودة تدخل جسمه ولا تلمس ما تحت الذيل."""
    for j in range(i0, i1):
        in_ret = ret and ret[0] <= j <= ret[1]
        floor = ZB + (ZT - ZB) * 0.18 if in_ret else ZT + ra * 0.015
        W[j]["l"] = max(W[j]["l"], floor)
        W[j]["o"] = max(W[j]["o"], W[j]["l"])
        W[j]["c"] = max(W[j]["c"], W[j]["l"])
        W[j]["h"] = max(W[j]["h"], max(W[j]["o"], W[j]["c"]))
        if in_ret:
            W[j]["l"] = min(W[j]["l"], ZT - (ZT - ZB) * 0.3)

