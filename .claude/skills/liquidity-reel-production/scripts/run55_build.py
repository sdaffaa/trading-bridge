HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out55")
os.makedirs(OUT, exist_ok=True)

CW, CH = 940, 560          # لوحة الشارت داخل صفحة المحتوى
HW, HH = 900, 430          # لوحة الغلاف


def _src(f, extra=""):
    return (f'{f["name"]} · {f["tf"]} · Alpha Vantage'
            + (f' · {extra}' if extra else ""))


# ══════════════════════════════════════════════════════════════
# ١ · «عقدة» — درس تعليمي · بروفايل الحجم + الحجم
# ══════════════════════════════════════════════════════════════
def c1(f):
    B, P_ = f["bars"], f["prof"]
    i0, i1 = f["i0"], f["i1"]
    end = min(len(B) - 1, i1 + 40)

    def prof_chart(W, H, a, z, marks=True, vol=0, prof=190):
        pn = Panel(B, a, z, W, H, pad=dict(l=14, r=92, t=26, b=40),
                   vol_h=vol, prof_w=prof).fin()
        s = pn.grid() + pn.profile(P_, poc=False,
                                   marks=[(f["lvn_p"], RED, "رقيقة"),
                                          (f["hvn_p"], EDU, "سميكة")] if marks else [])
        s += pn.candles() + pn.volume() + pn.times()
        return pn, s

    # ── غلاف ──
    pn, body = prof_chart(HW, HH, i0, end, prof=150)
    body += pn.hline(f["hvn_p"], EDU, 1.8, "6 5", ends=False)
    body += pn.hline(f["lvn_p"], RED, 1.8, "6 5", ends=False)
    hero = svg(HW, HH, body)
    s1 = P.cover(["بروفايل الحجم", "الحجم"],
                 'عبَرها بيوم… وقعد فوق الثانية <b>١٨ يوم</b>.<br>ليش الفرق؟',
                 'نفس الشارت، مستويان. الفرق مو بالسعر — بالحجم اللي '
                 '<b>تراكم</b> عند كل واحد.',
                 hero, _src(f, f'{dnum(f["a"])} → {dnum(f["z"])}'))

    # ── ٢ التعريف ──
    pn, body = prof_chart(CW, 500, i0, i1, prof=205)
    body += pn.hline(f["hvn_p"], EDU, 2.2, None, ends=False)
    body += pn.label(f["hvn_p"], f'عقدة سميكة {num(f["hvn_p"])}', EDU, side="left")
    body += pn.hline(f["lvn_p"], RED, 2.2, "7 5", ends=False)
    body += pn.label(f["lvn_p"], f'عقدة رقيقة {num(f["lvn_p"])}', RED, up=False, side="left")
    s2 = P.page(2, "التعريف", "العقدة = كم حجم تداول عند هذا السعر بالضبط",
                'البروفايل يقلب المحور: بدل الحجم تحت الزمن، الحجم '
                '<b class="t">بجانب السعر</b>. الطويل عقدة سميكة، والقصير رقيقة.',
                svg(CW, 500, body),
                'بروفايل <b>محسوب من شموع يومية</b>: حجم كل يوم موزَّع على مداه '
                '— تقريب معلَن، لا بيانات تِك.')

    # ── ٣ كيف تتكوّن ──
    pn, body = prof_chart(CW, 520, i0, i1, marks=False, vol=110, prof=0)
    body += pn.hline(P_["poc_price"], EDU, 2.0, "6 5", ends=False)
    body += pn.label(P_["poc_price"], f'POC {num(P_["poc_price"])}', EDU, side="left")
    body += pn.hline(P_["vah"], SUB, 1.5, "4 5", ends=False)
    body += pn.label(P_["vah"], f'VAH {num(P_["vah"])}', SUB, side="left")
    body += pn.hline(P_["val"], SUB, 1.5, "4 5", ends=False)
    body += pn.label(P_["val"], f'VAL {num(P_["val"])}', SUB, up=False, side="left")
    s3 = P.page(3, "كيف تتكوّن",
                "السعر اللي يتكرر فيه التداول يكبّر عقدته",
                'كل يوم يوزّع حجمه على مداه. السعر اللي يمرّ عليه السوق '
                '<b>مرّات كثيرة</b> يجمع حجماً أكبر — وهذي العقدة السميكة.',
                svg(CW, 520, body),
                f'نطاق ثابت معلَن: {dnum(f["a"])} → {dnum(f["z"])} · '
                f'⁦{f["i1"] - f["i0"] + 1}⁩ شمعة · منطقة القيمة ٧٠٪ من الحجم.')

    # ── ٤ المثال ──
    a2 = f["i1"] - 6
    pn = Panel(B, a2, len(B) - 1, CW, 520,
               pad=dict(l=14, r=92, t=26, b=40)).ext(lo=f["lvn_p"]).fin()
    body = pn.grid() + pn.candles() + pn.times()
    body += pn.hline(f["hvn_p"], EDU, 2.2, None, ends=False)
    body += pn.label(f["hvn_p"], f'السميكة — لمسَتها ⁦{f["t_hvn"]}⁩ شمعة', EDU, side="left")
    body += pn.hline(f["lvn_p"], RED, 2.2, "7 5", ends=False)
    body += pn.label(f["lvn_p"], f'الرقيقة — لمسَتها ⁦{f["t_lvn"]}⁩ شمعات', RED,
                     up=False, side="left")
    s4 = P.page(4, "المثال — شموع حقيقية",
                "بعد النطاق: العبور سريع والقعود عند السميكة",
                'خلال <b>⁦48⁩ شمعة</b> بعد النطاق: الرقيقة لمسَتها ⁦4⁩ شموع فقط، '
                'والسميكة <b class="t">⁦18⁩</b>.',
                svg(CW, 520, body) + P.stats([
                    ("لمسات الرقيقة", "4"), ("إغلاقات داخلها", "1"),
                    ("لمسات السميكة", "18"), ("إغلاقات داخلها", "4")]))

    # ── ٥ أخطاء القراءة ──
    s5 = P.page(5, "أخطاء القراءة",
                "العقدة مو دعم ولا مقاومة مضمونة",
                'هي <b>خريطة حجم</b> تقول وين السوق تفاوض كثير ووين مرّ بسرعة '
                '— ما تقول وين ينعكس.',
                P.checks([
                    "العقدة السميكة تبطّئ السعر — ما توقفه. لا تبني عليها وحدها.",
                    "العقدة الرقيقة تُعبر بسرعة في الاتجاهين — مو إشارة شراء.",
                    "لا تغيّر بداية النطاق ونهايته لين تطلع النتيجة اللي تبيها.",
                    "فرّق: قبول = إغلاقات داخل العقدة · رفض = لمسة وخروج.",
                ]),
                'أي بروفايل بلا نطاقٍ معلَن — بدايته ونهايته — رقمٌ بلا معنى.')

    return [s1, s2, s3, s4, s5,
            P.cta("عقدة",
                  "احفظه كخطوة أولى قبل ما ترسم أي مستوى على الشارت.",
                  "أرسله لمتداول يرسم دعوماً بالمسطرة بلا حجم.")]


# ══════════════════════════════════════════════════════════════
# ٢ · «مرساة» — خطوات دخول · ICT + VWAP المرسى
# ══════════════════════════════════════════════════════════════
def c2(f):
    B = f["bars"]
    # §4: الشرح التعليمي ٢٠–٤٠ شمعة. نافذة `facts` الضيّقة (١٤) تكفي
    # للقياس ولا تكفي للقراءة على الجوال، فتُوسَّع للعرض وحده — الأرقام
    # نفسها بلا تغيير.
    i0 = max(0, f["p"] - 13)
    i1 = min(len(B) - 1, f["hit"] + 9)
    avp = [(k, f["av"][k]) for k in range(f["anchor"], i1 + 1)]

    def base(W, H, a=None, z=None, vw=True, pad=None):
        pn = Panel(B, a or i0, z or i1, W, H,
                   pad=pad or dict(l=14, r=92, t=26, b=40))
        pn.ext(lo=f["stop"], hi=f["tgt"]).fin()
        s = pn.grid() + pn.candles()
        if vw:
            s += pn.line([(k, v) for k, v in avp if (a or i0) <= k <= (z or i1)],
                         EDU, 2.4, "8 5")
        s += pn.times()
        return pn, s

    # ── غلاف ──
    pn, body = base(HW, HH, pad=dict(l=14, r=88, t=24, b=38))
    body += pn.hline(f["lvl"], RED, 1.8, "6 5", ends=False)
    body += pn.hline(f["tgt"], GRN, 1.8, "6 5", ends=False)
    body += pn.mark(f["s"], B[f["s"]]["l"], RED, 12)
    hero = svg(HW, HH, body)
    s1 = P.cover(["ICT", "VWAP المرسى"],
                 'كسر القاع… وأغلق فوقه بنفس اليوم.<br>هذي <b>غارة</b> مو انهيار.',
                 'خمس خطوات من السيولة إلى الهدف — وكل رقم فيها من شموع '
                 '<b>حقيقية</b>.',
                 hero, _src(f, f'{dnum(B[f["p"]]["d"])} → {dnum(B[f["hit"]]["d"])}'))

    # ── ٢ السياق ──
    pn, body = base(CW, 500)
    body += pn.label(f["av"][f["s"]], f'VWAP مرسى {num(f["av"][f["s"]])}', EDU)
    body += pn.arrow(f["anchor"], B[f["anchor"]]["h"], up=True, col=SUB)
    body += t(pn.x(f["anchor"]), pn.y(B[f["anchor"]]["h"]) - 46,
              "المرساة", SUB, 19, 600)
    s2 = P.page(2, "الخطوة ١ — السياق",
                "المرساة أولاً: من أي شمعة نحسب متوسط السعر بالحجم",
                'خط VWAP المرسى يبدأ من حدثٍ نختاره — هنا <b>قاع '
                f'{dnum(B[f["anchor"]]["d"][5:])}</b>. فوق الخط علاوة، تحته '
                '<b class="t">خصم</b>.',
                svg(CW, 500, body),
                'المرساة تُعلَن دائماً. VWAP بلا نقطة بداية معروفة = خطٌّ '
                'ما تعرف من وين جاء.')

    # ── ٣ موقع السيولة ──
    pn, body = base(CW, 500, vw=False)
    body += pn.hline(f["lvl"], RED, 2.2, None, ends=False)
    body += pn.label(f["lvl"], f'سيولة البيع {num(f["lvl"])}', RED)
    body += pn.hline(f["tgt"], GRN, 2.0, "7 5", ends=False)
    body += pn.label(f["tgt"], f'سيولة الشراء {num(f["tgt"])}', "#4E8E4C")
    body += pn.mark(f["p"], B[f["p"]]["l"], RED, 11)
    s3 = P.page(3, "الخطوة ٢ — موقع السيولة",
                "تحت القاع أوامر وقف، وفوق القمّة أوامر وقف",
                'سيولة البيع (Sell-Side) تحت القاع، وسيولة الشراء (Buy-Side) '
                'فوق القمّة. <b>هذي وجهات</b>، مو دخول.',
                svg(CW, 500, body),
                'ICT: تحديد السيولة يسبق استعمالها. مستوى بلا تعريف = خطٌّ فقط.')

    # ── ٤ التنفيذ والتأكيد ──
    pn, body = base(CW, 500)
    body += pn.hline(f["lvl"], RED, 2.0, None, x1=pn.x(f["s"]) + pn.slot,
                     ends=False)
    body += pn.mark(f["s"], B[f["s"]]["l"], RED, 12)
    body += pn.mark(f["s"], f["ent"], EDU, 12)
    body += pn.label(f["ent"], f'إغلاق فوق المستوى {num(f["ent"])}', EDU)
    body += t(pn.x(f["s"]), pn.y(B[f["s"]]["l"]) + 42,
              f'اختراق {num(B[f["s"]]["l"])}', RED, 19, 700)
    s4 = P.page(4, "الخطوة ٣ — الشرط والتأكيد",
                "اخترق القاع بفتيله… وأغلق فوقه",
                'الشرط: <b>الفتيل تحت</b> والإغلاق فوق. والتأكيد الثاني: '
                'الإغلاق تحت خط VWAP بـ<b class="t">'
                f'⁦{f["disc"]:.2f}⁩٪</b> — أي في الخصم.',
                svg(CW, 500, body),
                f'حجم شمعة الغارة ⁦{f["rel"]:.2f}⁩× المتوسط — <b>عادي، لا ذروة</b>. '
                'ولذلك ما نبني عليه وحده.')

    # ── ٥ الخطة ──
    pn, body = base(CW, 430, pad=dict(l=14, r=92, t=22, b=36))
    x0 = pn.x(f["s"]) - pn.slot * 0.6
    body += (f'<rect x="{x0:.1f}" y="{pn.y(f["ent"]):.1f}" '
             f'width="{pn.px1 - x0:.1f}" '
             f'height="{pn.y(f["stop"]) - pn.y(f["ent"]):.1f}" fill="{RED}" '
             f'opacity="0.13"/>'
             f'<rect x="{x0:.1f}" y="{pn.y(f["tgt"]):.1f}" '
             f'width="{pn.px1 - x0:.1f}" '
             f'height="{pn.y(f["ent"]) - pn.y(f["tgt"]):.1f}" fill="{GRN}" '
             f'opacity="0.18"/>')
    body += pn.hline(f["ent"], EDU, 2.0, None, ends=False)
    body += pn.label(f["ent"], f'دخول {num(f["ent"])}', EDU)
    body += pn.hline(f["stop"], RED, 1.8, "6 5", ends=False)
    body += pn.label(f["stop"], f'إبطال {num(f["stop"])}', RED, up=False, side="left")
    body += pn.hline(f["tgt"], "#4E8E4C", 1.8, "6 5", ends=False)
    body += pn.label(f["tgt"], f'هدف {num(f["tgt"])}', "#4E8E4C")
    body += pn.mark(f["hit"], f["tgt"], "#4E8E4C", 11)
    s5 = P.page(5, "الخطوة ٤ — الإبطال والهدف",
                "الوقف تحت فتيل الغارة، والهدف سيولة الشراء",
                f'الهدف تحقّق بعد <b class="t">⁦{f["bars_to_target"]}⁩ شمعتين</b>، '
                f'وأدنى قاع بينهما {num(f["low_after"])} — فوق الوقف.',
                svg(CW, 430, body) + P.plan_table([
                    ("الدخول — إغلاق الغارة", num(f["ent"]), "t"),
                    ("الإبطال — تحت الفتيل", num(f["stop"]), "r"),
                    ("الهدف — سيولة الشراء", num(f["tgt"]), ""),
                    ("المخاطرة مقابل المكافأة", f'⁦{f["rr"]:.1f}⁩R', "t"),
                ]),
                'المسافة كبيرة لأن <b>الوقف ضيّق</b> — ⁦0.35⁩٪ فقط. حالة واحدة '
                'لا قاعدة، ونموذج تعليمي لا توصية.', tone="warn")

    return [s1, s2, s3, s4, s5,
            P.cta("مرساة",
                  "احفظه كترتيب خطوات: مرساة ← سيولة ← إغلاق ← إبطال ← هدف.",
                  "أرسله لمن يدخل على الكسر بلا إغلاق يؤكّده.")]


# ══════════════════════════════════════════════════════════════
# ٣ · «امتصاص» — تشريح خسارة · SMC + فوت برنت (رسم توضيحي)
# ══════════════════════════════════════════════════════════════
def c3(f):
    B = f["bars"]
    i0, i1 = f["i0"], f["i1"]

    def base(W, H, vol=0, pad=None):
        pn = Panel(B, i0, i1, W, H, pad=pad or dict(l=14, r=92, t=26, b=40),
                   vol_h=vol).fin()
        return pn, pn.grid() + pn.candles() + pn.volume(
            hi_i={f["br"]}) + pn.times()

    # ── غلاف ──
    pn, body = base(HW, HH, pad=dict(l=14, r=88, t=24, b=38))
    body += pn.hline(B[f["hi"]]["h"], SUB, 1.6, "5 5", ends=False)
    body += pn.mark(f["br"], f["ent"], EDU, 12)
    body += pn.mark(f["fail"], B[f["fail"]]["c"], RED, 12)
    hero = svg(HW, HH, body)
    s1 = P.cover(["SMC", "فوت برنت"],
                 'كسر الهيكل… وانعكس مباشرة.<br><b>شنو فاتك؟</b>',
                 'صفقة تبدو صحيحة بالكامل — والدليل اللي كان يوقفها كان '
                 '<b>مكتوباً على الشارت</b>.',
                 hero, _src(f, f'{dnum(B[f["hi"]]["d"])} → {dnum(B[f["fail"]]["d"])}'))

    # ── ٢ ليش بدت صحيحة ──
    pn, body = base(CW, 500)
    body += pn.hline(B[f["hi"]]["h"], INK, 2.0, None,
                     x1=pn.x(f["br"]) + pn.slot, ends=False)
    body += pn.label(B[f["hi"]]["h"], f'قمّة مرجعية {num(B[f["hi"]]["h"])}', INK)
    body += pn.arrow(f["br"], f["ent"], up=True, col=EDU)
    body += t(pn.x(f["br"]), pn.y(f["ent"]) - 46, "BOS", EDU, 21, 700,
              rtl=False)
    s2 = P.page(2, "التشريح ١",
                "ليش بدت الصفقة صحيحة؟",
                f'قمّة مرجعية واضحة عند {num(B[f["hi"]]["h"])}، وإغلاق فوقها في '
                f'<b>{dnum(B[f["br"]]["d"][5:])}</b> عند {num(f["ent"])}. '
                'كسر هيكل بالكتاب.',
                svg(CW, 500, body),
                'SMC: الكسر يُقاس على <b>قمّة محدّدة</b> — لا على أي ارتفاع. '
                'وهنا القمّة محدّدة فعلاً.')

    # ── ٣ العلامة المتجاهَلة ──
    pn, body = base(CW, 520, vol=130)
    body += pn.hline(B[f["hi"]]["h"], SUB, 1.6, "5 5", ends=False)
    s3 = P.page(3, "التشريح ٢",
                "الدليل المتجاهَل: الكسر صار بحجم أقلّ من المتوسط",
                f'حجم شمعة الكسر <b class="r">⁦{f["rel"]:.2f}⁩×</b> متوسط عشرين '
                'يوماً — يعني <b>أقلّ</b> من العادي. كسرٌ بلا جهدٍ يسنده.',
                svg(CW, 520, body),
                'قاعدة: الحجم ما يعطي اتجاهاً وحده — لكن كسراً مهمّاً بحجمٍ '
                '<b>دون المتوسط</b> سؤالٌ لازم يُسأل.')

    # ── ٤ الفوت برنت (رسم توضيحي) ──
    # الصفوف تُظهر الشكل الذي يُدرَّس: شراءٌ عدواني يتضخّم كلّما ارتفع
    # السعر (٩٨٠ ← ٣٬١٤٠) والسعر لا يتقدّم فوق القمّة — بائعٌ يمتصّه.
    rows = [(724.00, 240, 3140), (723.50, 310, 2680), (723.00, 520, 1980),
            (722.50, 940, 1260), (722.00, 1310, 880)]
    fp = footprint(rows, 900, 470,
                   "شكل الامتصاص داخل شمعة الكسر",
                   "رسم توضيحي — وليس شارتاً حقيقياً · أرقام تعليمية")
    s4 = P.page(4, "ما لا تظهره الشمعة",
                "الامتصاص: شراء يتضخّم عند القمّة… والسعر ثابت",
                'الشمعة تعطيك أربعة أرقام. الفوت برنت يعطيك <b class="t">من '
                'اشترى ومن باع</b> عند كل سعر — والقراءة <b>قطرية</b>: آسك كل '
                'صفٍّ مقابل بِد الصفّ الذي فوقه.',
                fp,
                'ما عندنا مصدر عرضٍ وطلبٍ داخل الشمعة في هذا الخطّ — '
                '<b>فالأرقام أعلاه تعليمية</b> تشرح الشكل، لا سوقاً.',
                tone="warn")

