def _rp_p(t):
    """فهرس الشمعة الجارية عند اللحظة t — نسخة بايثون من دالّة المحرّك."""
    for i in range(len(RP_KF) - 1):
        (ta, pa), (tb, pb) = RP_KF[i], RP_KF[i + 1]
        if t <= tb:
            return pa + (pb - pa) * max(0.0, min(1.0, (t - ta) / (tb - ta)))
    return RP_KF[-1][1]


