def _clampx(cx, half):
    """يبقي وسماً موسَّطاً داخل اللوحة: نصف عرضه لا يتجاوز أي حافة.

    بلا هذا يُقصّ الرقم عند الحافة كلما وقع الحدث في طرف النافذة —
    والرقم المقصوص أسوأ من الوسم المزاح."""
    return min(max(cx, PL + half), CVW - PR - half)


def chip(xr, yc, txt, col, fs=30):
    """وسمٌ على خلفية معتمة — كما ترسم المنصّة وسوم الأوامر فوق الشموع.

    كان «تنفيذ» يُرفع فوق أعلى قمّة مجاورة كي لا يقع داخل الأجساد. وبستّين
    شمعة صار جوار الدخول أعلى بكثير، فطار الوسم إلى ثلث اللوحة العلوي
    وانفصل عن السهم الذي يصفه. والحلّ ليس ملاحقة القمم بإزاحات: الوسم
    يُلصق بسعر الدخول وتُوضع تحته خلفية، فما تحته لا يزاحمه.

    `xr` الحافة اليمنى (العربية تُقرأ من اليمين) و`yc` مركز الوسم رأسياً."""
    w = len(txt) * fs * 0.58 + 26
    h = fs + 16
    return (f'<rect x="{xr-w:.1f}" y="{yc-h/2:.1f}" width="{w:.1f}" height="{h:.1f}" '
            f'fill="{tv_chart.T["BG"]}" fill-opacity=".93" stroke="{col}" '
            f'stroke-width="1.5" stroke-opacity=".45" rx="2"/>'
            + htext(xr - 13, yc + fs * 0.34, txt, col, fs, anchor="start"))


