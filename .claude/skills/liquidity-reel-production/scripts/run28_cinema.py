def scale_of(w, plo=None, pt=0.08):
    """حدود محور السعر. `plo` مضاعف الهامش السفلي — والفرق ليس تجميلاً:

    لوحة التنفيذ تحتاج تحته صفّين من الوسوم (سحب السيولة وذيل الرفض)
    فيبقى هامشها واسعاً (١٫٤٥ — قِيس على أدنى الوسمين لا بالتقدير،
    ويحرسه `assert` أدناه). أما لوحات الفريمات الأعلى فلا وسم تحتها،
    وهامشٌ بمقدار ١٫٧ يترك ربع اللوحة السفلي بياضاً لا شمعة فيه."""
    lo = min(c["l"] for c in w); hi = max(c["h"] for c in w)
    pad = (hi - lo) * pt
    return lo - pad * (PLO if plo is None else plo), hi + pad


def geo(w, plo=None, pt=0.08, vis=None):
    ymin, ymax = scale_of(w, plo, pt)
    slot = PW / (vis or len(w))
    return (lambda i: PL + slot * i + slot / 2,
            lambda p: PT + (ymax - p) / (ymax - ymin) * PH, slot, ymin, ymax)


def panel(gid, w, sym, tf, extra="", dec=2, plo=0.55):
    """لوحة فريم في مجموعتين: **هيكل** (خلفية وشبكة ومحور) ثم **محتوى**
    (شموع وماركب).

    🔒 أمر فهد 2026-08-08: «طريقة التغيير بين الفريمات سيئة». وكانت
    مجموعةً واحدة تذوب فوق جارت التنفيذ في أربعة أعشار الثانية — فيظهر
    الجارتان معاً نصفَ شفافين: محوران وشمعتان في كل موضع وعلامةٌ مائية
    مزدوجة. ذلك «مزج» لا يقع في منصّة قط.

    فصلُ الهيكل عن المحتوى يعطي التبديل شكله الحقيقي: تُنقر الشريحة،
    فيقطع الهيكل المعتم فوق ما كان (لا مزج، لأنه معتم من أول إطار)،
    وتبقى اللوحة فارغة جزءاً من الثانية — وهي لحظة التحميل التي تراها في
    المنصّة — ثم تهبط الشموع دفعةً واحدة."""
    x, y, slot, ymin, ymax = geo(w, plo)
    T = tv_chart.T
    o = [f'<g id="{gid}s" opacity="0">',
         f'<rect x="0" y="0" width="{CVW}" height="{CVH}" fill="{T["BG"]}"/>']
    # شبكة + محور سعر
    import math
    # سبعة مستويات لا خمسة: بالهامش الضيّق صار المدى أصغر، و`_step` كانت
    # تعطي خطّين اثنين على اللوحة كلها — محورٌ لا يُقرأ منه سعر.
    st = tv_chart._step(ymax - ymin, 7)
    v = (int(ymin / st) + 1) * st
    while v < ymax:
        yy = y(v)
        o.append(f'<line x1="{PL}" y1="{yy:.1f}" x2="{CVW-PR}" y2="{yy:.1f}" '
                 f'stroke="{T["GRID"]}" stroke-width="1.4"/>')
        o.append(f'<text x="{CVW-PR+9}" y="{yy+6:.1f}" fill="{T["AXTX"]}" font-size="19" '
                 f'font-weight="600" font-family="system-ui,sans-serif" direction="ltr">{v:,.{dec}f}</text>')
        v += st
    o.append(f'<line x1="{CVW-PR}" y1="{PT}" x2="{CVW-PR}" y2="{CVH-PB}" '
             f'stroke="{T["AXBD"]}" stroke-width="1.6"/>')
    o.append(f'<line x1="{PL}" y1="{CVH-PB}" x2="{CVW-PR}" y2="{CVH-PB}" '
             f'stroke="{T["AXBD"]}" stroke-width="1.6"/>')
    # وسم الرمز الباهت
    o.append(f'<text x="{(PL+CVW-PR)/2:.0f}" y="{PT+PH*0.45:.0f}" fill="{T["WMK"]}" '
             f'font-size="120" font-weight="900" text-anchor="middle" '
             f'font-family="system-ui,sans-serif">{tf}</text>')
    # شريط الرمز والفريم — من الهيكل: يظهر مع المحور قبل الشموع، كما
    # تفعل المنصّة حين تُعلن الفريم الجديد وهي بعدُ تُحمّل بياناته.
    o.append(f'<text x="{PL+4}" y="{PT-34}" fill="{T["LEGT"]}" font-size="26" font-weight="800" '
             f'font-family="system-ui,sans-serif" direction="ltr">{sym}  ·  {tf}</text>')
    o.append(f'</g><g id="{gid}" opacity="0">')
    # شموع
    bw = slot * 0.6
    BULL, BEAR = ("#43D4DC", "#5E7A88") if DK else ("#2E8CA6", "#122F3E")
    for i, c in enumerate(w):
        cx = x(i); up = c["c"] >= c["o"]; col = BULL if up else BEAR
        top, bot = y(max(c["o"], c["c"])), y(min(c["o"], c["c"]))
        o.append(f'<line x1="{cx:.1f}" y1="{y(c["h"]):.1f}" x2="{cx:.1f}" y2="{y(c["l"]):.1f}" '
                 f'stroke="{col}" stroke-width="2.4"/>'
                 f'<rect x="{cx-bw/2:.1f}" y="{top:.1f}" width="{bw:.1f}" '
                 f'height="{max(bot-top,2.4):.1f}" fill="{col}" rx="1"/>')
    o.append(extra)
    o.append("</g>")
    return "".join(o)


